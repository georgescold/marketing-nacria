def trim_frame(im, limit=.16):
    """Remove white margins and drawn panel borders: strip edge rows/columns that are uniform (low spread), up to 16%."""
    import numpy as np
    a = np.asarray(im.convert("L"), dtype=float)
    h, w = a.shape

    def depth(lines, n):
        k = 0
        while k < int(n * limit) and lines(k).std() < 14:
            k += 1
        return k + (4 if k else 0)

    top = depth(lambda k: a[k, :], h)
    bottom = depth(lambda k: a[h - 1 - k, :], h)
    left = depth(lambda k: a[:, k], w)
    right = depth(lambda k: a[:, w - 1 - k], w)
    return im.crop((left, top, w - right, h - bottom))


def story_slide(src, dst):
    im = trim_frame(Image.open(src).convert("RGB"))
    r = W / H
    if im.width / im.height < r:  # too tall: crop top/bottom
        h = round(im.width / r)
        y = (im.height - h) // 2
        im = im.crop((0, y, im.width, y + h))
    else:
        w = round(im.height * r)
        x = (im.width - w) // 2
        im = im.crop((x, 0, x + w, im.height))
    im.resize((W, H), Image.LANCZOS).save(dst)


