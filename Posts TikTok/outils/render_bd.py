def render_cta(vis, cfg, dst):
    tmp = R.HERE / "_html_bd"
    tmp.mkdir(exist_ok=True)
    css, body = cta_follow(vis, cfg) if CTA_MODE == "follow" else cta(vis, cfg, tmp)
    h = tmp / (dst.parent.name.replace(" ", "_") + "_cta.html")
    h.write_text(f'<!doctype html><html><head><meta charset="utf-8"><style>{css}</style></head><body>{body}</body></html>', encoding="utf-8")
    R.subprocess.run([R.CHROME, "--headless=new", "--disable-gpu", "--hide-scrollbars", "--force-device-scale-factor=1",
                      f"--window-size={W},{H}", f"--screenshot={dst}", "--virtual-time-budget=3000", h.as_uri()],
                     check=True, capture_output=True, timeout=120)


def main(vis, out):
    vis, out = pathlib.Path(vis).resolve(), pathlib.Path(out).resolve()
    out.mkdir(parents=True, exist_ok=True)
    for k in range(1, 8):
        story_slide(vis / f"s{k}.png", out / f"slide_{k:02d}.png")
    render_cta(vis, POSTS.get(out.name, DEFAULT), out / "slide_08.png")
    print("ok", out)


